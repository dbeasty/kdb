/**
 * Attachments against Go's fixtures: packages/kdb-replica/test/golden/attachments.json (generated by
 * go/cmd/kdb-tsfixtures from Go's AttachmentTable, as the TS replica checks them) and the pinned
 * values of go/kdb/document/attachment_golden_test.go.
 */
class AttachmentTest {
    private val f = golden("attachments.json").obj

    private fun refOf(o: JsonObject) =
        AttachmentRef(o["scheme"]!!.jsonPrimitive.long.toInt(), KdbHash.fromBytes(hex32(o.s("contentHash"))), o["size"]!!.jsonPrimitive.long, o.s("mime"))

    private fun opOf(o: JsonObject): KdbOp {
        val doc = KdbUuid.fromString(o.s("docId"))
        return when (o.s("kind")) {
            "write" -> KdbOp.Write(doc, o.s("json"))
            "delete" -> KdbOp.Delete(doc)
            "attachmentPut" ->
                KdbOp.AttachmentPut(
                    doc,
                    KdbUuid.fromString(o.s("attachmentId")),
                    o.s("name"),
                    o["scheme"]!!.jsonPrimitive.long.toInt(),
                    KdbHash.fromBytes(hex32(o.s("contentHash"))),
                    o["size"]!!.jsonPrimitive.long,
                    o.s("mime"),
                )
            "attachmentDelete" -> KdbOp.AttachmentDelete(doc, KdbUuid.fromString(o.s("attachmentId")))
            else -> error("unknown fixture op ${o.s("kind")}")
        }
    }

    /** The fixture generator's bytes (go/cmd/kdb-tsfixtures/attachments.go). */
    private fun fixtureBytes(o: JsonObject): ByteArray {
        if (o["helloText"] != null) return o.s("helloText").encodeToByteArray()
        val size = o["size"]!!.jsonPrimitive.long.toInt()
        val seed = o["seed"]!!.jsonPrimitive.long.toInt()
        return ByteArray(size) { i -> ((i * 31 + seed * 7 + (i shr 8)) and 0xff).toByte() }
    }

    @Test
    fun refAndSetHashesAreGos() {
        for (r in f["refs"]!!.arr.map { it.obj }) assertEquals(r.s("refHash"), refOf(r).hash().toHex())
        for (s in f["sets"]!!.arr.map { it.obj }) {
            val set =
                s["entries"]!!.arr.map { it.obj }.map { e ->
                    val ref = refOf(e["ref"]!!.obj)
                    ReplicaAttachment(e.s("id"), e.s("name"), ref.scheme, ref.contentHash.toHex(), ref.size, ref.mime)
                }
            assertEquals(s.s("setHash"), attachmentSetHash(set))
            assertEquals(s.s("setHash"), attachmentSetHash(set.reversed()), "a set's hash does not depend on the order given")
        }
        // go/kdb/document/attachment_golden_test.go's pins
        assertEquals("365f1bd0c0b790d6812664a83229589447f5a9a3156bfa137b65320621ff0a68", f["refs"]!!.arr[0].obj.s("refHash"))
        assertEquals("dd3ca4b42f1408538c2e5a1c84c888b6670fb9da99b2029a80eb9c8d411630d4", f["sets"]!!.arr[0].obj.s("setHash"))
    }

    @Test
    fun blobsStoreUnderGosContentHashInChunks() =
        runBlocking {
            val store = MemoryReplicaStore()
            val blobs = BlobStore(store)
            for (c in f["contentHashes"]!!.arr.map { it.obj }) {
                val data = fixtureBytes(c)
                val hash = blobs.putLocal(data)
                assertEquals(c.s("hash"), hash, c.s("name"))
                assertTrue(blobs.complete(hash) && blobs.pinned(hash), c.s("name"))
                assertContentEquals(data, blobs.read(hash), c.s("name"))
                val chunks = store.scan("b/$hash/", prefixEnd("b/$hash/"))
                assertEquals(chunkCount(data.size.toLong()).toInt(), chunks.size, "${c.s("name")}: 1 MiB chunks")
                assertTrue(chunks.all { it.second.size <= ATTACHMENT_CHUNK_BYTES })
            }
            assertEquals("cf1b6c96f0fcdb59fffdc5a353309421c73530cf0639f595d3a42546131c168b", blobs.putLocal("hello".encodeToByteArray()))
        }

    @Test
    fun theTableRootAfterEveryStepIsGos() =
        runBlocking {
            val store = MemoryReplicaStore()
            // kdb-document's resident AttachmentTable, applied alongside, agrees at every step too.
            var resident = AttachmentTable.EMPTY
            for ((i, step) in f["table"]!!.arr.map { it.obj }.withIndex()) {
                val ops = step["ops"]!!.arr.map { opOf(it.obj) }
                val edit = AttachmentEdit(store, "ns")
                edit.apply(ops)
                assertEquals(step.s("root"), edit.finish().orEmpty(), "step $i")
                store.apply(Batch().also(edit::writeTo))
                assertEquals(step.s("root"), attachmentRootOf(store, "ns").orEmpty(), "step $i reread")
                resident = resident.apply(ops)
                assertEquals(step.s("root"), resident.root?.toHex().orEmpty(), "step $i resident")
            }
            // The stored sets are the resident table's.
            for (doc in resident.documentIds) {
                assertEquals(resident.list(doc).map { it.toReplica() }, attachmentsOf(store, "ns", doc.toString()))
            }
        }

    @Test
    fun aPutRefusesANameAnotherAttachmentHas() =
        runBlocking {
            val store = MemoryReplicaStore()
            val doc = KdbUuid.random()
            val h = KdbHash.fromBytes(ByteArray(32) { 1 })
            val edit = AttachmentEdit(store, "ns")
            edit.apply(listOf(KdbOp.AttachmentPut(doc, KdbUuid.random(), "a.txt", 1, h, 3, "text/plain")))
            assertFailsWith<AttachmentException> {
                edit.apply(listOf(KdbOp.AttachmentPut(doc, KdbUuid.random(), "a.txt", 1, h, 3, "text/plain")))
            }
            assertFailsWith<AttachmentException> { AttachmentEdit(store, "ns").apply(listOf(KdbOp.AttachmentPut(doc, KdbUuid.random(), "b", 2, h, 3, ""))) }
            Unit
        }

    @Test
    fun attachmentCommitsAreGosByteForByte() {
        for (c in f["commits"]!!.arr.map { it.obj }) {
            val payload = hexToBytes(c.s("payloadHex"))
            val rc = ReplicaCommit.decode(payload)
            assertEquals(c.s("hash"), rc.hash, c.s("name"))
            assertEquals(c.s("attachmentRoot"), rc.attachmentRoot, c.s("name"))
            assertEquals(c["ops"]!!.arr.map { opOf(it.obj) }, rc.ops, c.s("name"))
            assertContentEquals(payload, rc.commit.toPayloadBytes(), c.s("name"))
        }
        val golden = f["commits"]!!.arr.map { it.obj }.single { it.s("name") == "attachmentGolden" }
        assertEquals("ca9ab1ab70b327ae4cbc9092c4a87a55e10a1d47c6fcac17b72e0ded7beee9c3", golden.s("hash"))
        // And the replica's own builder writes the same bytes.
        val built =
            ReplicaCommit.build(
                parents = golden["parents"]!!.arr.map { it.jsonPrimitive.content },
                namespace = golden.s("namespace"),
                transactionId = KdbUuid.fromString(golden.s("transactionId")),
                timestampMicros = golden.s("timestampMicros").toLong(),
                authorNodeId = KdbUuid.fromString(golden.s("authorNodeId")),
                ops = golden["ops"]!!.arr.map { opOf(it.obj) },
                treeHash = golden.s("treeHash"),
                message = golden.s("message"),
                attachmentRoot = golden.s("attachmentRoot"),
            )
        assertEquals(golden.s("hash"), built.hash)
    }

    @Test
    fun aPackedTableParsesToItsSets() {
        val doc = KdbUuid.random()
        val a = Attachment(KdbUuid.random(), "x.bin", AttachmentRef(1, KdbHash.fromBytes(ByteArray(32) { 7 }), 9, "application/octet-stream"))
        val b = Attachment(KdbUuid.random(), "y.bin", AttachmentRef(1, KdbHash.fromBytes(ByteArray(32) { 8 }), 0, ""))
        val t = AttachmentTable.EMPTY.put(doc, a).put(doc, b)
        val parsed = parsePackedAttachmentTable(AttachmentTable.pack(listOf(t)))
        assertEquals(setOf(doc.toString()), parsed.keys)
        assertEquals(t.list(doc).hash().toHex(), attachmentSetHash(parsed.getValue(doc.toString())))
        assertEquals(emptyMap(), parsePackedAttachmentTable(ByteArray(0)))
    }

    @Test
    fun aLocalCommitCarriesItsAttachmentRootAndAFastForwardVerifiesIt() =
        runBlocking {
            val ns = ReplicaNamespace.open(MemoryReplicaStore(), "app/att", ATT_NODE)
            val doc = KdbUuid.random()
            val h = KdbHash.fromBytes(ByteArray(32) { 5 })
            val att = KdbUuid.random()
            val c = ns.commitLocal(listOf(KdbOp.Write(doc, "{}"), KdbOp.AttachmentPut(doc, att, "a", 1, h, 10, "text/plain")), KdbUuid.random())
            val table = AttachmentTable.EMPTY.put(doc, Attachment(att, "a", AttachmentRef(1, h, 10, "text/plain")))
            assertEquals(table.root?.toHex(), c.attachmentRoot)
            assertEquals(c.attachmentRoot, ns.attachmentRoot())
            assertEquals(listOf("a"), ns.attachments(doc.toString()).map { it.name })

            // A second replica fast-forwards to it; a forged root is refused and writes nothing.
            val other = ReplicaNamespace.open(MemoryReplicaStore(), "app/att", ATT_NODE)
            val forged =
                ReplicaCommit.build(c.parents, "app/att", KdbUuid.random(), c.timestampMicros, KdbUuid.random(), c.ops, c.treeHash, "", "ab".repeat(32))
            assertFailsWith<AttachmentRootMismatchException> { other.fastForward(listOf(forged), forged.hash) }
            assertNull(other.attachmentRoot())
            other.fastForward(listOf(c), c.hash)
            assertEquals(c.attachmentRoot, other.attachmentRoot())

            // A document delete takes the document's attachments with it.
            val d = ns.commitLocal(listOf(KdbOp.Delete(doc)), KdbUuid.random())
            assertNull(d.attachmentRoot)
            assertEquals(emptyList(), ns.attachments(doc.toString()))
            assertEquals(DocumentTree.EMPTY.treeHash.toHex(), d.treeHash)
        }
}

private const val ATT_NODE = "99999999-9999-4999-8999-999999999998"
