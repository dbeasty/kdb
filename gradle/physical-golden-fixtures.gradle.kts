// Compiles the physical-layer golden fixtures (go/testdata/golden/physical/{go,kotlin}/*.hex) into
// a Kotlin source, so commonTest - and with it Kotlin/JS (node and browser) and Kotlin/Native,
// which have no portable file API in tests - can read the bytes Go and the JVM wrote.
// docs/kdb-physical-layer-compat-test-plan.md §6.
//
// A module opts in with:
//
//   apply(from = rootProject.file("gradle/physical-golden-fixtures.gradle.kts"))
//   kotlin { sourceSets { commonTest { kotlin.srcDir(tasks.named("generatePhysicalGoldenFixtures")) } } }
//
// and reads `dev.kdb.golden.PhysicalGoldenFixtures.read("go", "sstable_segment.hex")`. The fixtures
// stay the single source of truth: this is regenerated whenever one of them changes, and the JVM
// tests keep reading the files directly.

val physicalGoldenDir: File = rootProject.file("go/testdata/golden/physical")
val physicalGoldenOut: Provider<Directory> = layout.buildDirectory.dir("generated/physicalGolden/commonTest/kotlin")

tasks.register("generatePhysicalGoldenFixtures") {
    val sourceDir = physicalGoldenDir
    val outDir = physicalGoldenOut
    inputs.dir(sourceDir).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(outDir)
    doLast {
        val entries =
            listOf("go", "kotlin").flatMap { side ->
                (File(sourceDir, side).listFiles { f -> f.name.endsWith(".hex") } ?: emptyArray())
                    .sortedBy { it.name }
                    .map { "$side/${it.name}" to it.readText().trim() }
            }
        val body =
            entries.joinToString(",\n") { (key, hex) ->
                // JVM class files cap one string constant at 65535 bytes.
                val chunks = hex.chunked(32_000).joinToString(", ") { "\"$it\"" }
                "        \"$key\" to listOf<String>($chunks)"
            }
        val file = outDir.get().file("dev/kdb/golden/PhysicalGoldenFixtures.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by gradle/physical-golden-fixtures.gradle.kts from go/testdata/golden/physical. Do not edit.
            |package dev.kdb.golden
            |
            |internal object PhysicalGoldenFixtures {
            |    /** The bytes of `go/testdata/golden/physical/<side>/<name>`, or null when it does not exist. */
            |    fun read(side: String, name: String): ByteArray? = files["${'$'}side/${'$'}name"]?.let { decode(it.joinToString("")) }
            |
            |    /** Every fixture name on [side]. */
            |    fun names(side: String): List<String> = files.keys.filter { it.startsWith("${'$'}side/") }.map { it.substringAfter('/') }
            |
            |    private fun decode(hex: String): ByteArray = ByteArray(hex.length / 2) { hex.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
            |
            |    private val files: Map<String, List<String>> = mapOf(
            |$body,
            |    )
            |}
            |""".trimMargin(),
        )
    }
}
