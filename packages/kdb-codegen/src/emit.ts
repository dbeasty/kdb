/**
 * The TypeScript emitter. Node-only (it hashes with node:crypto), so it lives behind the
 * `@limidus/kdb-codegen/generate` subpath and never reaches an application bundle.
 */

import { createHash } from "node:crypto";
import { createTableSql, type FieldDef, type SchemaFile, type TableSchema } from "./schema.ts";

export interface GenerateOptions {
  /** Shown in the header so a reader can find the source of truth. */
  source?: string;
}

const DOC_TYPE: Record<FieldDef["kind"], string> = {
  string: "string",
  int32: "number",
  int64: "number",
  float64: "number",
  bool: "boolean",
  timestamp: "string",
  uuid: "string",
  object: "Record<string, unknown>",
  array: "unknown[]",
  enum: "string",
};

function docType(f: FieldDef): string {
  if (f.kind === "enum") return (f.values ?? []).map((v) => JSON.stringify(v)).join(" | ");
  return DOC_TYPE[f.kind];
}

function camel(input: string): string {
  const parts = input.split("_").filter((p) => p !== "");
  const joined = parts.map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1))).join("");
  return joined === "" ? "table" : joined;
}

function column(f: FieldDef): string {
  const values = f.kind === "enum" ? `, values: [${(f.values ?? []).map((v) => JSON.stringify(v)).join(", ")}]` : "";
  return `    ${f.name}: { kind: ${JSON.stringify(f.kind)}, required: ${f.required}${values} },`;
}

function emitTable(t: TableSchema): string {
  const doc = t.fields
    .map((f) => (f.required ? `  ${f.name}: ${docType(f)};` : `  ${f.name}?: ${docType(f)} | null;`))
    .join("\n");
  const note = t.fields.some((f) => f.kind === "int64")
    ? "\n * int64 fields are `number` here: document bodies are JSON, which cannot carry a bigint. SQL rows\n * return them as `bigint` (see select())."
    : "";
  const varName = camel(t.table);
  return `/**
 * Document body for namespace ${JSON.stringify(t.namespace)}.${note}
 */
export interface ${t.typeName} {
${doc}
}

export const ${varName} = defineTable<${t.typeName}>()({
  namespace: ${JSON.stringify(t.namespace)},
  table: ${JSON.stringify(t.table)},
  columns: {
${t.fields.map(column).join("\n")}
  },
  createSql: ${JSON.stringify(createTableSql(t))},
});
`;
}

export function schemaDigest(file: SchemaFile): string {
  return createHash("sha256").update(JSON.stringify(file)).digest("hex");
}

export function generate(file: SchemaFile, options: GenerateOptions = {}): string {
  const bindings = file.tables.map((t) => `    ${camel(t.table)}: ${camel(t.table)}.bind(ops),`).join("\n");
  const source = options.source === undefined ? "" : ` from ${options.source}`;
  return `// Code generated by @limidus/kdb-codegen${source}. DO NOT EDIT.
// schema-sha256: ${schemaDigest(file)}
//
// Regenerate with \`kdb-codegen\`; \`kdb-codegen --check\` fails when this file is stale.

import type { KdbOperations } from "@limidus/kdb-client";
import { defineTable } from "@limidus/kdb-codegen";

${file.tables.map(emitTable).join("\n")}
/** Binds every generated table to a client (or an embedded runtime - anything implementing KdbOperations). */
export function bind(ops: KdbOperations) {
  return {
${bindings}
  };
}
`;
}
